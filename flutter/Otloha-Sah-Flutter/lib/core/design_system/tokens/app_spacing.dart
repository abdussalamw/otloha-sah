import 'package:flutter/material.dart';

/// AppSpacing defines standard 8pt grid spacing tokens for Otloha Sah.
abstract class AppSpacing {
  static const double xs = 4.0;
  static const double sm = 8.0;
  static const double md = 16.0;
  static const double lg = 24.0;
  static const double xl = 32.0;
  static const double xxl = 48.0;

  // EdgeInsets helpers
  static const EdgeInsets paddingAllXs = EdgeInsets.all(xs);
  static const EdgeInsets paddingAllSm = EdgeInsets.all(sm);
  static const EdgeInsets paddingAllMd = EdgeInsets.all(md);
  static const EdgeInsets paddingAllLg = EdgeInsets.all(lg);
  static const EdgeInsets paddingAllXl = EdgeInsets.all(xl);

  static const EdgeInsets paddingSymmetricHorizontalMd = EdgeInsets.symmetric(horizontal: md);
  static const EdgeInsets paddingSymmetricHorizontalLg = EdgeInsets.symmetric(horizontal: lg);
  static const EdgeInsets paddingSymmetricVerticalMd = EdgeInsets.symmetric(vertical: md);

  // SizedBox spacing helpers
  static const SizedBox gapXs = SizedBox(width: xs, height: xs);
  static const SizedBox gapSm = SizedBox(width: sm, height: sm);
  static const SizedBox gapMd = SizedBox(width: md, height: md);
  static const SizedBox gapLg = SizedBox(width: lg, height: lg);
  static const SizedBox gapXl = SizedBox(width: xl, height: xl);
}
